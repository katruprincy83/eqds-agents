#!/usr/bin/env python3
"""Resolve the app dependency pins into fully pinned lock files, requirements/<kind>.lock.

`scripts/build_apps.py` pins only the top-level packages (PINS / REQ). The Databricks Apps builder then runs `pip install -r` and has to
solve every transitive package itself; when a new upstream release does not fit, pip backtracks through hundreds of old versions and the
app never starts ("App process did not start within 15 minutes"). The lock files list every package at an exact version, so the build is
one plain install. They are resolved for what the Apps builder runs: Linux x86_64, Python 3.11.

    python scripts/lock_requirements.py            # rewrite requirements/*.lock from PINS / REQ
    python scripts/lock_requirements.py --check    # fail if a lock is stale or missing (used by the tests)
"""
from __future__ import annotations

import argparse
import pathlib
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
import build_apps  # noqa: E402

LOCK_DIR = ROOT / "requirements"
PYTHON_VERSION = "3.11"
PLATFORM = "x86_64-manylinux_2_17"


def top_level(kind: str) -> str:
    return "\n".join(f"{p}=={build_apps.PINS[p]}" for p in build_apps.REQ[kind]) + "\n"


def resolve(kind: str) -> str:
    with tempfile.TemporaryDirectory() as d:
        src = pathlib.Path(d) / f"{kind}.in"
        src.write_text(top_level(kind))
        out = subprocess.run(
            ["uv", "pip", "compile", str(src), "--python-version", PYTHON_VERSION, "--python-platform", PLATFORM,
             "--no-annotate", "--no-header", "-q"],
            capture_output=True, text=True,
        )
    if out.returncode:
        sys.exit(f"uv could not resolve {kind}:\n{out.stderr}")
    header = f"# {kind}: generated by scripts/lock_requirements.py (Python {PYTHON_VERSION}, {PLATFORM}); do not edit by hand\n"
    return header + out.stdout


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="verify the committed locks still pin every top-level package")
    a = ap.parse_args()
    LOCK_DIR.mkdir(exist_ok=True)
    bad = []
    for kind in build_apps.REQ:
        path = LOCK_DIR / f"{kind}.lock"
        if a.check:
            if not path.exists():
                bad.append(f"{path.name} is missing")
                continue
            pinned = {l.split("==")[0].lower(): l.split("==")[1].strip() for l in path.read_text().splitlines() if "==" in l}
            for p in build_apps.REQ[kind]:
                name = p.split("[")[0].lower().replace("_", "-")
                if pinned.get(name) != build_apps.PINS[p]:
                    bad.append(f"{path.name}: {name} is {pinned.get(name)}, PINS says {build_apps.PINS[p]}")
        else:
            path.write_text(resolve(kind))
            print(f"wrote {path.relative_to(ROOT)} ({sum('==' in l for l in path.read_text().splitlines())} packages)")
    if bad:
        print("\n".join(bad))
        print("run: python scripts/lock_requirements.py")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
