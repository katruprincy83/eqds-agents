#!/usr/bin/env python3
"""`make infra TARGET=<t>`: platform prerequisites that DABs do not own (design §4.2). Idempotent.

Creates, when absent, from `config/env/<target>.yaml`:
  * UC catalog                  (schemas / volumes are created by `bundle deploy`)
  * secret scope + secrets      (VALUES come from env vars, never from the repository)
  * Lakebase Autoscaling project + database, and (when `lakebase.branch` is not `production`) that branch, created from `production`
  * UC schema for traces (`traces_schema`, when `flags.use_uc_trace_storage`)
  * Vector Search endpoint
  * (optional) service principals listed in `service_principals` when the value is a name that does not exist

Secret env vars (all optional if the scope already holds the key):
  EQDS_AZURE_SQL_USER / EQDS_AZURE_SQL_PASSWORD               -> azure-sql-user / azure-sql-password
  EQDS_AZURE_SQL_SEED_USER / EQDS_AZURE_SQL_SEED_PASSWORD     -> azure-sql-seed-user / azure-sql-seed-password
                                                                 (default: same as above)
  EQDS_YOUDOTCOM_API_KEY                                      -> <web_search.secret_key> (when web_search.mode=vendor)
  (job-caller-client-id<suffix> / job-caller-client-secret<suffix> are generated by `make infra` for the `<prefix>-job-caller<suffix>` service principal;
 the eval and wiki jobs use it to call the moderator app because Apps reject notebook tokens)
"""
from __future__ import annotations

import argparse
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "packages", "eqds_agentkit"))

from databricks.sdk import WorkspaceClient  # noqa: E402
from databricks.sdk.errors import NotFound, ResourceAlreadyExists  # noqa: E402
from databricks.sdk.service import catalog as uc  # noqa: E402
from databricks.sdk.service import vectorsearch as vs  # noqa: E402

from eqds_agentkit.envcfg import Env  # noqa: E402


def client(env: Env, profile: str | None) -> WorkspaceClient:
    if profile or os.environ.get("DATABRICKS_CONFIG_PROFILE"):
        return WorkspaceClient(profile=profile or os.environ["DATABRICKS_CONFIG_PROFILE"])
    return WorkspaceClient(host=env.host)


def say(ok: str, msg: str) -> None:
    print(f"  [{ok}] {msg}", flush=True)


def ensure_catalog(w: WorkspaceClient, env: Env) -> None:
    try:
        w.catalogs.get(env.catalog)
        say("ok", f"catalog {env.catalog} exists")
    except NotFound:
        kw = {}
        if env.get("catalog_storage_root"):
            kw["storage_root"] = env.get("catalog_storage_root")
        w.catalogs.create(name=env.catalog, comment=f"{env.prefix} ({env.target}) catalog", **kw)
        say("created", f"catalog {env.catalog}")


def ensure_schemas(w: WorkspaceClient, env: Env) -> None:
    """The environment schema is created by `bundle deploy` (resources/uc/schemas.yml); the traces schema has to exist BEFORE an experiment
    is bound to it (MLflow does not create it), so it is created here."""
    if not env.get("flags.use_uc_trace_storage"):
        return
    name = env.traces_schema
    try:
        w.schemas.get(f"{env.catalog}.{name}")
        say("ok", f"schema {env.catalog}.{name} exists")
    except NotFound:
        w.schemas.create(name=name, catalog_name=env.catalog, comment=f"{env.prefix} ({env.target}) MLflow traces")
        say("created", f"schema {env.catalog}.{name} (traces)")


def ensure_workspace_dirs(w: WorkspaceClient, env: Env) -> None:
    import posixpath

    parent = posixpath.dirname(env.experiment_path)
    w.workspace.mkdirs(parent)
    say("ok", f"workspace folder {parent}")


def ensure_secrets(w: WorkspaceClient, env: Env) -> None:
    scope = env.secret_scope
    try:
        w.secrets.create_scope(scope=scope)
        say("created", f"secret scope {scope}")
    except ResourceAlreadyExists:
        say("ok", f"secret scope {scope} exists")
    existing = {s.key for s in w.secrets.list_secrets(scope=scope)}
    user = os.environ.get("EQDS_AZURE_SQL_USER")
    pwd = os.environ.get("EQDS_AZURE_SQL_PASSWORD")
    wanted = {
        "azure-sql-user": user, "azure-sql-password": pwd,
        "azure-sql-seed-user": os.environ.get("EQDS_AZURE_SQL_SEED_USER", user),
        "azure-sql-seed-password": os.environ.get("EQDS_AZURE_SQL_SEED_PASSWORD", pwd),
    }
    if env.get("web_search.mode") == "vendor":
        wanted[env.get("web_search.secret_key", "youdotcom-api-key")] = os.environ.get("EQDS_YOUDOTCOM_API_KEY")
    for k, v in wanted.items():
        if v:
            w.secrets.put_secret(scope=scope, key=k, string_value=v)
            say("set", f"secret {scope}/{k} (from env var)")
        elif k in existing:
            say("ok", f"secret {scope}/{k} already present")
        elif env.external_db_mode != "off" and k.startswith("azure-sql"):
            say("MISSING", f"secret {scope}/{k}: export EQDS_AZURE_SQL_USER / EQDS_AZURE_SQL_PASSWORD and re-run")


def ensure_lakebase(w: WorkspaceClient, env: Env) -> None:
    from databricks.sdk.service.postgres import Database, DatabaseDatabaseSpec, Project, ProjectSpec

    proj = env.lakebase_project
    try:
        w.postgres.get_project(name=f"projects/{proj}")
        say("ok", f"lakebase project {proj} exists")
    except NotFound:
        w.postgres.create_project(project=Project(spec=ProjectSpec(display_name=proj, pg_version=17)), project_id=proj).wait()
        say("created", f"lakebase project {proj}")
    ensure_lakebase_branch(w, env)
    branch = f"projects/{proj}/branches/{env.get('lakebase.branch', 'production')}"
    dbname = env.lakebase_database
    dbs = list(w.postgres.list_databases(parent=branch))
    if any(d.status and d.status.postgres_database == dbname for d in dbs):
        say("ok", f"lakebase database {dbname} exists")
    else:
        db_id = dbname.replace("_", "-")
        try:
            owner = next((d.status.role for d in dbs if d.status and d.status.role), None)   # owner = the project creator's role
            w.postgres.create_database(parent=branch, database=Database(spec=DatabaseDatabaseSpec(postgres_database=dbname, role=owner)), database_id=db_id).wait()
            say("created", f"lakebase database {dbname}")
        except ResourceAlreadyExists:
            say("ok", f"lakebase database {dbname} exists")


LB_DATA_SCHEMAS = ["registry", "mem", "ops", "bridge", "lg"]    # schemas holding runtime data (the migrations seed no rows)


def ensure_lakebase_branch(w: WorkspaceClient, env: Env) -> None:
    """A non-production environment (dev) works on its own Lakebase branch of the same project. The branch is created from
    `production` (copy-on-write: schemas, roles and migration state come along), gets its own read-write endpoint, and its RUNTIME DATA
    is reset once, at creation: the copied registry rows point at production specialist apps, and the copied runs and memory are
    production's. Later runs find the branch and touch nothing."""
    from databricks.sdk.service.postgres import Branch, BranchSpec, Endpoint, EndpointSpec, EndpointType

    proj = env.lakebase_project
    name = env.get("lakebase.branch", "production")
    parent = f"projects/{proj}"
    if name == "production":
        return
    bname = f"{parent}/branches/{name}"
    created = False
    try:
        w.postgres.get_branch(name=bname)
        say("ok", f"lakebase branch {name} exists")
    except NotFound:
        src = env.get("lakebase.source_branch", "production")
        w.postgres.create_branch(parent=parent, branch=Branch(spec=BranchSpec(source_branch=f"{parent}/branches/{src}", no_expiry=True)), branch_id=name).wait()
        say("created", f"lakebase branch {name} (from {src})")
        created = True
    if not any(e.status and e.status.endpoint_type and "READ_WRITE" in str(e.status.endpoint_type) for e in w.postgres.list_endpoints(parent=bname)):
        w.postgres.create_endpoint(parent=bname, endpoint=Endpoint(spec=EndpointSpec(endpoint_type=EndpointType.ENDPOINT_TYPE_READ_WRITE)), endpoint_id="primary").wait()
        say("created", f"lakebase endpoint on {name}")
    if created:
        reset_lakebase_data(w, env)


def reset_lakebase_data(w: WorkspaceClient, env: Env) -> None:
    from eqds_agentkit import lakebase

    t = lakebase.resolve(env.lakebase_project, env.get("lakebase.branch", "production"), env.lakebase_database, w=w)
    conn = lakebase.connect(t)
    rows = conn.execute("SELECT schemaname, tablename FROM pg_tables WHERE schemaname = ANY(%s)", (LB_DATA_SCHEMAS,)).fetchall()
    if rows:
        conn.execute("TRUNCATE " + ", ".join(f'"{r["schemaname"]}"."{r["tablename"]}"' for r in rows) + " RESTART IDENTITY CASCADE")
    conn.close()
    say("reset", f"lakebase branch {t.branch}: runtime data cleared in {len(rows)} tables (registry, mem, ops, bridge, lg)")


def ensure_vector_search(w: WorkspaceClient, env: Env) -> None:
    name = env.vs_endpoint
    try:
        w.vector_search_endpoints.get_endpoint(name)
        say("ok", f"vector search endpoint {name} exists")
    except NotFound:
        w.vector_search_endpoints.create_endpoint(name=name, endpoint_type=vs.EndpointType.STANDARD)
        say("created", f"vector search endpoint {name} (provisioning asynchronously)")


def ensure_service_principals(w: WorkspaceClient, env: Env) -> None:
    for role, sp in (env.get("service_principals") or {}).items():
        if not sp:
            continue
        found = list(w.service_principals.list(filter=f'displayName eq "{sp}"'))
        if found:
            say("ok", f"service principal {sp}")
        else:
            w.service_principals.create(display_name=sp, active=True)
            say("created", f"service principal {sp} ({role})")


def ensure_job_caller(w: WorkspaceClient, env: Env) -> None:
    """Service principal + OAuth secret used by batch jobs (eval, wiki) to call the moderator app; secret lives only in the secret scope."""
    name = f"{env.prefix}-job-caller{env.suffix}"
    found = list(w.service_principals.list(filter=f'displayName eq "{name}"'))
    from databricks.sdk.service.iam import ComplexValue, Patch, PatchOp, PatchSchema

    sp = found[0] if found else w.service_principals.create(display_name=name, active=True)
    say("ok" if found else "created", f"service principal {name}")
    if "workspace-access" not in {e.value for e in (sp.entitlements or [])}:   # without it Apps answer the SP with an OAuth redirect
        w.service_principals.patch(id=str(sp.id), schemas=[PatchSchema.URN_IETF_PARAMS_SCIM_API_MESSAGES_2_0_PATCH_OP],
                                   operations=[Patch(op=PatchOp.ADD, path="entitlements", value=[{"value": "workspace-access"}])])
        say("set", f"{name}: workspace-access entitlement")
    keys = {s.key for s in w.secrets.list_secrets(env.secret_scope)}
    kid, ksec = env.job_caller_secret_keys
    if ksec in keys and kid in keys:
        say("ok", "job-caller secret present")
        return
    sec = w.service_principal_secrets_proxy.create(service_principal_id=str(sp.id))
    w.secrets.put_secret(scope=env.secret_scope, key=kid, string_value=sp.application_id)
    w.secrets.put_secret(scope=env.secret_scope, key=ksec, string_value=sec.secret)
    say("set", f"secret {env.secret_scope}/{kid}|{ksec} (generated)")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--target", default=os.environ.get("TARGET", "demo"))
    ap.add_argument("--profile", default=None)
    ap.add_argument("--skip", nargs="*", default=[], help="catalog schemas dirs secrets lakebase vs sps jobcaller")
    a = ap.parse_args()
    env = Env.from_target(a.target)
    w = client(env, a.profile)
    print(f"infra target={env.target} host={env.host}")
    steps = [("catalog", ensure_catalog), ("schemas", ensure_schemas), ("dirs", ensure_workspace_dirs), ("secrets", ensure_secrets), ("lakebase", ensure_lakebase),
             ("vs", ensure_vector_search), ("sps", ensure_service_principals), ("jobcaller", ensure_job_caller)]
    for name, fn in steps:
        if name in a.skip:
            continue
        print(f"- {name}")
        fn(w, env)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
